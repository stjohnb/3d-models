"""Tests for spec_pages.py and the pages/ spec-pages tree.

The figures on each project spec page are inline SVG generated by Node
scripts in pages/<project>/src/. These tests fail when a committed SVG
differs from its generator's output, when the page's inline figures differ
from the committed SVGs, or when a page loads an external asset. Node comes
from the flake's devShell in CI.

Run with: python3 -m unittest test_spec_pages
"""

import pathlib
import re
import shutil
import sys
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import spec_pages  # noqa: E402

NODE = shutil.which("node")


def pages():
    return [spec_pages.PAGES_ROOT / "index.html",
            *sorted(spec_pages.PAGES_ROOT.glob("*/index.html"))]


class GeneratorTests(unittest.TestCase):
    @unittest.skipUnless(NODE, "node is not on PATH (the flake devShell provides it)")
    def test_committed_svgs_match_generators(self):
        for project in spec_pages.GENERATORS:
            with self.subTest(project=project):
                self.assertEqual(spec_pages.check_generators(project), [])

    def test_page_figures_match_committed_svgs(self):
        for project in spec_pages.GENERATORS:
            with self.subTest(project=project):
                self.assertEqual(spec_pages.check_page(project), [])

    def test_every_project_page_has_generators(self):
        dirs = {p.parent.name for p in spec_pages.PAGES_ROOT.glob("*/index.html")}
        self.assertEqual(dirs, set(spec_pages.GENERATORS))


class SelfContainedTests(unittest.TestCase):
    def test_pages_load_no_external_assets(self):
        for page in pages():
            with self.subTest(page=page.relative_to(spec_pages.REPO_ROOT)):
                self.assertEqual(spec_pages.external_refs(page.read_text(encoding="utf-8")), [])

    def test_external_refs_detects_loads_but_not_links(self):
        html = ('<a href="https://x/">x</a><svg><line marker-end="url(#da)"/></svg>'
                '<img src="a.png"><script></script><style>@import "b.css"</style>')
        self.assertEqual(spec_pages.external_refs(html),
                         ["<img", " src=", "<script", "@import"])

    def test_index_links_every_project(self):
        index = (spec_pages.PAGES_ROOT / "index.html").read_text(encoding="utf-8")
        links = set(re.findall(r'href="\./([^"/]+)/"', index))
        projects = {p.parent.name for p in spec_pages.PAGES_ROOT.glob("*/index.html")}
        self.assertTrue(projects)
        self.assertEqual(links, projects)


class SpliceTests(unittest.TestCase):
    def test_splice_round_trips(self):
        html = "<p>a</p><svg>1</svg><p>b</p><svg x>2</svg>"
        self.assertEqual(spec_pages.inline_svgs(html), ["<svg>1</svg>", "<svg x>2</svg>"])
        out = spec_pages.splice(html, ["<svg>3</svg>", "<svg>4</svg>"])
        self.assertEqual(out, "<p>a</p><svg>3</svg><p>b</p><svg>4</svg>")
        self.assertEqual(spec_pages.splice(out, spec_pages.inline_svgs(html)), html)

    def test_splice_rejects_count_mismatch(self):
        with self.assertRaises(ValueError):
            spec_pages.splice("<svg>1</svg>", [])


if __name__ == "__main__":
    unittest.main()
